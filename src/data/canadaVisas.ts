function buildVisaItems(list: any[], cat: string): VisaItem[] {
  return list.map(v => {
    const micro = getCanadaMicroDetails(v.id, cat, v.name);
    const docs = getCanadaDocs(v.id, cat, v.name);
    return {
      id: v.id,
      officialCode: v.officialCode,
      officialName: v.officialName,
      name: v.name,
      categoryCode: cat,
      fee: v.fee,
      validity: v.validity,
      stay: v.stay,
      processing: v.processing,
      purpose: v.purpose,
      eligibility: v.eligibility,
      popular: v.popular,
      highlight: v.highlight,
      isActive: v.isActive,
      isLegacy: v.isLegacy || false,
      officialSource: v.officialSource,
      ...micro,
      docs
    };
  });
}

