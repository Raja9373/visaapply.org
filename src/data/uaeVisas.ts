function buildUaeVisaItems(list: typeof uaeRawVisas, cat: string): VisaItem[] {
  return list.map(v => {
    const micro = getUaeMicroDetails(v.id, cat, v.name);
    const docs = getUaeDocs(v.id, cat, v.name);

    const iconMap: Record<string, string> = {
      tourist: "🇦🇪",
      work: "💼",
      student: "🎓",
      family: "👨‍👩‍👧",
      business: "🤝",
      pr: "🏛️"
    };

    return {
      id: v.id,
      officialCode: v.officialCode,
      officialName: v.officialName,
      name: v.name,
      categoryCode: cat,
      icon: v.popular ? "⭐" : (iconMap[cat] || "🇦🇪"),
      fee: v.fee,
      validity: v.validity,
      stay: v.stay,
      processing: v.processing,
      purpose: v.purpose,
      eligibility: v.eligibility,
      popular: v.popular,
      highlight: v.highlight,
      isActive: v.isActive,
      isLegacy: v.isLegacy,
      record_type: v.record_type as any,
      officialSource: v.officialSource,
      ...micro,
      docs,
      documents: docs,
      infoReq: [
        "1. Personal Biographic Information (Full Legal Name, Date & Place of Birth, Nationality, Passport Details)",
        "2. Passport Credentials (Passport Number, Issue Date, Expiry Date, Issuing Authority)",
        "3. UAE Residence / Contact Details (Hotel booking, Host invitation, or UAE residential address)",
        "4. Sponsor / Employer / Institution Details (MOHRE Employer ID, Free Zone Authority, University, or Family Sponsor Emirates ID)",
        "5. Financial & Employment Profile (Salary certificate, Bank statements, or Investment valuation)",
        "6. Family Background & Civil Status (Marriage certificate, Birth certificates for dependents)",
        "7. UAE Immigration Suitability & Medical Fitness (Medical fitness screening test, Emirates ID biometric registration)"
      ],
      steps: [
        "1. Check UAE visa route eligibility & gather all mandatory documents (attested degree, passport, bank statement, or title deed).",
        "2. Submit application online via GDRFA Dubai portal (for Dubai) or ICP Smart Services portal (for other emirates), or through an authorized typing center / travel agent.",
        "3. Pay official UAE visa processing and entry permit fees online.",
        "4. Receive entry permit (eVisa) via email for entering the UAE.",
        "5. Enter the UAE and complete in-country status change (if applicable without exit), medical fitness screening, and biometrics for Emirates ID.",
        "6. Receive official UAE Residence Visa stamp / digital confirmation and Emirates ID card."
      ],
      tips: [
        "UAE uses a dual-authority immigration system: GDRFA Dubai handles Dubai entries, while ICP (Federal Authority) handles Abu Dhabi, Sharjah, Ajman, UAQ, RAK, and Fujairah.",
        "For 5-Year Tourist Visa or property/investment visas, ensure financial statements are organic and seasoned for 6 months without sudden 1-day cash deposits.",
        "Ensure university degrees and marriage/birth certificates are duly attested by the UAE Embassy in your home country and UAE MOFA before submission."
      ],
      faq: [
        {
          q: `What is the official fee and processing time for ${v.name} (${v.officialCode})?`,
          a: `The official fee is ${v.fee}, and standard processing takes ${v.processing} via GDRFA Dubai or ICP Smart Services.`
        },
        {
          q: `What are the key financial requirements or document proofs for ${v.name}?`,
          a: micro.fundsBox.minimum + " " + micro.fundsBox.bankMonths
        },
        {
          q: `What are the most important mandatory documents for ${v.name}?`,
          a: `Key mandatory documents include: ${docs.slice(0, 5).join('; ')}.`
        }
      ]
    };
  });
}

